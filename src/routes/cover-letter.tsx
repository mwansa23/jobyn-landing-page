import { createFileRoute } from "@tanstack/react-router";
import { useEffect, useMemo, useState } from "react";
import { Check, Copy, Download, FileText, Loader2, Shield, Sparkles, Wand2 } from "lucide-react";
import { Card } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Textarea } from "@/components/ui/textarea";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Navbar } from "@/components/Navbar";
import { Footer } from "@/components/Footer";
import { ApiError } from "@/lib/api";
import {
  downloadGeneratedText,
  fetchJobOptions,
  generateCoverLetterForJob,
  loadGeneratedArtifact,
  saveGeneratedArtifact,
  type JobOption,
} from "@/lib/applications";
import { fetchCandidateProfile, getCandidateId } from "@/lib/candidate-profile";

export const Route = createFileRoute("/cover-letter")({
  head: () => ({
    meta: [
      { title: "AI Cover Letter — Jobyn AI" },
      {
        name: "description",
        content:
          "Generate a tailored cover letter in seconds. Jobyn AI matches your CV to the job description and writes application-ready copy.",
      },
      { property: "og:title", content: "AI Cover Letter — Jobyn AI" },
      {
        property: "og:description",
        content: "Tailored, application-ready cover letters generated by AI from your CV.",
      },
      { property: "og:type", content: "website" },
      { name: "twitter:card", content: "summary_large_image" },
    ],
  }),
  component: CoverLetterPage,
});

function CoverLetterPage() {
  const [jobs, setJobs] = useState<JobOption[]>([]);
  const [jobId, setJobId] = useState("");
  const [role, setRole] = useState("");
  const [company, setCompany] = useState("");
  const [jd, setJd] = useState("");
  const [letter, setLetter] = useState("");
  const [generating, setGenerating] = useState(false);
  const [copied, setCopied] = useState(false);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [candidateName, setCandidateName] = useState("");

  useEffect(() => {
    void (async () => {
      try {
        const items = await fetchJobOptions();
        setJobs(items);
        if (items[0]) {
          setJobId(items[0].id);
          setRole(items[0].title);
          setCompany(items[0].company_name);
        }

        const candidateId = getCandidateId();
        if (candidateId) {
          const profile = await fetchCandidateProfile(candidateId);
          setCandidateName(profile.name || "Your profile");
        }

        const savedLetter = loadGeneratedArtifact("jobyn.cover_letter");
        if (savedLetter) setLetter(savedLetter);
      } catch (err) {
        setError(err instanceof ApiError ? err.message : "Unable to load jobs or profile data.");
      } finally {
        setLoading(false);
      }
    })();
  }, []);

  const selectedJob = useMemo(() => jobs.find((item) => item.id === jobId) ?? null, [jobId, jobs]);

  const generate = async () => {
    if (!jobId && !(role || company)) {
      setError(
        "Please choose a job or provide a role and company before generating the cover letter.",
      );
      return;
    }

    setGenerating(true);
    setError(null);

    try {
      const result = await generateCoverLetterForJob({
        jobId: jobId || undefined,
        role: role || selectedJob?.title,
        company: company || selectedJob?.company_name,
        jobDescription: jd,
        candidateId: getCandidateId() ?? undefined,
      });
      const text = result.cover_letter ?? result.content ?? result.text ?? result.letter ?? "";
      setLetter(text);
      saveGeneratedArtifact("jobyn.cover_letter", text);
    } catch (err) {
      setError(err instanceof ApiError ? err.message : "Unable to generate the cover letter.");
    } finally {
      setGenerating(false);
    }
  };

  const copy = async () => {
    if (!letter) return;
    await navigator.clipboard.writeText(letter);
    setCopied(true);
    setTimeout(() => setCopied(false), 1600);
  };

  return (
    <div className="flex min-h-screen flex-col bg-background">
      <Navbar />
      <main className="flex-1">
        <section className="border-b border-border/60 bg-gradient-to-b from-primary/[0.04] to-background">
          <div className="mx-auto max-w-6xl px-4 py-12 sm:px-6 sm:py-16 lg:px-8">
            <div className="flex items-center gap-2 text-sm font-medium text-primary">
              <Sparkles className="h-4 w-4" /> AI Cover Letter
            </div>
            <h1 className="mt-3 text-3xl font-bold tracking-tight text-foreground sm:text-4xl lg:text-5xl">
              Application-ready in one click
            </h1>
            <p className="mt-3 max-w-2xl text-lg text-muted-foreground">
              Select a job, use your existing candidate profile, and generate a cover letter
              tailored to the role.
            </p>
          </div>
        </section>

        <section className="mx-auto grid max-w-6xl gap-6 px-4 py-10 sm:px-6 sm:py-14 lg:grid-cols-5 lg:gap-8 lg:px-8">
          <Card className="p-6 lg:col-span-2">
            <h2 className="flex items-center gap-2 text-sm font-semibold uppercase tracking-wide text-foreground">
              <Wand2 className="h-4 w-4 text-primary" /> Job details
            </h2>
            <div className="mt-5 space-y-4">
              <div>
                <Label htmlFor="job-select">Select a job</Label>
                <select
                  id="job-select"
                  value={jobId}
                  onChange={(event) => {
                    const selected = event.target.value;
                    setJobId(selected);
                    const item = jobs.find((job) => job.id === selected);
                    setRole(item?.title ?? "");
                    setCompany(item?.company_name ?? "");
                  }}
                  className="mt-1.5 w-full rounded-md border border-input bg-background px-3 py-2 text-sm text-foreground"
                  disabled={loading}
                >
                  <option value="">Select a job</option>
                  {jobs.map((job) => (
                    <option key={job.id} value={job.id}>
                      {job.title} @ {job.company_name}
                    </option>
                  ))}
                </select>
              </div>
              <div>
                <Label htmlFor="role">Role</Label>
                <Input
                  id="role"
                  value={role}
                  onChange={(e) => setRole(e.target.value)}
                  className="mt-1.5"
                />
              </div>
              <div>
                <Label htmlFor="company">Company</Label>
                <Input
                  id="company"
                  value={company}
                  onChange={(e) => setCompany(e.target.value)}
                  className="mt-1.5"
                />
              </div>
              <div>
                <Label htmlFor="jd">Job description (optional)</Label>
                <Textarea
                  id="jd"
                  value={jd}
                  onChange={(e) => setJd(e.target.value)}
                  placeholder="Paste the JD here — the more detail, the better the letter."
                  className="mt-1.5 min-h-40"
                />
              </div>
              {candidateName && (
                <div className="rounded-lg border border-border/70 bg-muted/20 p-3 text-sm text-muted-foreground">
                  Using profile:{" "}
                  <span className="font-medium text-foreground">{candidateName}</span>
                </div>
              )}
              {error && (
                <p className="rounded-md border border-destructive/40 bg-destructive/5 px-3 py-2 text-sm text-destructive">
                  {error}
                </p>
              )}
              <Button
                onClick={() => void generate()}
                disabled={generating}
                className="w-full"
                size="lg"
              >
                {generating ? (
                  <>
                    <Loader2 className="mr-2 h-4 w-4 animate-spin" /> Generating…
                  </>
                ) : (
                  <>
                    <Sparkles className="mr-2 h-4 w-4" /> Generate cover letter
                  </>
                )}
              </Button>
            </div>
          </Card>

          <Card className="p-6 lg:col-span-3">
            <div className="flex items-center justify-between">
              <h2 className="flex items-center gap-2 text-sm font-semibold uppercase tracking-wide text-foreground">
                <FileText className="h-4 w-4 text-primary" /> Preview
              </h2>
              <div className="flex gap-2">
                <Button variant="outline" size="sm" onClick={copy} disabled={!letter}>
                  {copied ? (
                    <>
                      <Check className="mr-2 h-4 w-4" /> Copied
                    </>
                  ) : (
                    <>
                      <Copy className="mr-2 h-4 w-4" /> Copy
                    </>
                  )}
                </Button>
                <Button
                  variant="outline"
                  size="sm"
                  onClick={() => letter && downloadGeneratedText("cover-letter.txt", letter)}
                  disabled={!letter}
                >
                  <Download className="mr-2 h-4 w-4" /> Download
                </Button>
              </div>
            </div>
            <div className="mt-5 rounded-xl border border-border/70 bg-gradient-to-br from-background to-primary/[0.02] p-6">
              <pre className="whitespace-pre-wrap font-sans text-sm leading-relaxed text-foreground">
                {letter || "Choose a job and generate a cover letter to preview it here."}
              </pre>
            </div>
            <div className="mt-4 flex items-start gap-2 text-xs text-muted-foreground">
              <Shield className="mt-0.5 h-3.5 w-3.5 shrink-0 text-primary" />
              AI-generated. Please review before sending — a quick human pass catches nuance the
              model misses.
            </div>
          </Card>
        </section>
      </main>
      <Footer />
    </div>
  );
}
